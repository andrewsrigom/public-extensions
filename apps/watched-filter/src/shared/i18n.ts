export type I18nKey = keyof typeof DICTIONARIES.en;

export function resolveLanguage(preference: LanguagePreference = "auto"): SupportedLanguage {
  if (preference !== "auto") return preference;

  const locale = getBrowserLanguage().replace("_", "-").toLowerCase();
  if (locale.startsWith("pt")) return "pt-BR";
  if (locale.startsWith("es")) return "es";
  return "en";
}

export function getLocale(preference: LanguagePreference = "auto"): string {
  const language = resolveLanguage(preference);
  if (language === "pt-BR") return "pt-BR";
  if (language === "es") return "es";
  return "en";
}

export function t(
  key: I18nKey,
  preference: LanguagePreference = "auto",
  replacements: Record<string, string | number> = {}
): string {
  const language = resolveLanguage(preference);
  const message = DICTIONARIES[language][key] || DICTIONARIES.en[key] || key;

  return Object.entries(replacements).reduce(
    (current, [name, value]) => current.replaceAll(`{${name}}`, String(value)),
    message
  );
}

export function formatDateTime(value: string, preference: LanguagePreference = "auto"): string {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  return date.toLocaleString(getLocale(preference));
}

export function applyTranslations(root: ParentNode, preference: LanguagePreference = "auto"): void {
  const locale = getLocale(preference);
  document.documentElement.lang = locale;

  for (const element of root.querySelectorAll<HTMLElement>("[data-i18n]")) {
    const key = element.dataset.i18n as I18nKey | undefined;
    if (key) element.textContent = t(key, preference);
  }

  for (const element of root.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>("[data-i18n-placeholder]")) {
    const key = element.dataset.i18nPlaceholder as I18nKey | undefined;
    if (key) element.placeholder = t(key, preference);
  }

  for (const element of root.querySelectorAll<HTMLElement>("[data-i18n-title]")) {
    const key = element.dataset.i18nTitle as I18nKey | undefined;
    if (key) element.title = t(key, preference);
  }
}

function getBrowserLanguage(): string {
  const maybeChrome = (globalThis as { chrome?: { i18n?: { getUILanguage?: () => string } } }).chrome;

  try {
    return maybeChrome?.i18n?.getUILanguage?.() || navigator.language || "en";
  } catch {
    return navigator.language || "en";
  }
}
